# Команда С может быть применена только к числам, кратным трём, и уменьшает число на экране в три раза.
# Программа для исполнителя — это последовательность команд.
# Сколько программ преобразуют число 103 в число 24, и при этом их траектория вычислений содержит число 73?
# Траектория вычислений программы — это последовательность результатов выполнения всех команд программы. Например, для программы АСВ при исходном числе 251 траектория состоит из чисел 246, 82, 81.

# Идея решения: так как траектория должна обязательно содержать число 73,
# задачу можно разбить на две независимые части: найти количество программ от 103 до 73 
# и умножить на количество программ от 73 до 24. 
# Рекурсивная функция считает пути: если число равно целевому, возвращаем 1; 
# если стало меньше целевого, возвращаем 0. 
# Для чисел, не кратных 3, доступны команды А (вычесть 5) и В (вычесть остаток от деления на 3). 
# Для кратных 3 доступны команды А (вычесть 5) и С (разделить на 3).

def f(n, t):
    # Базовый случай: достигли целевого числа, найден 1 путь.
    if n == t:
        return 1
    
    # Если число стало меньше целевого, дальнейшее уменьшение бессмысленно, возвращаем 0.
    if n < t:
        return 0
    
    # Если число не кратно трём, доступны команды А (вычесть 5) и В (вычесть остаток от деления на 3, чтобы сделать кратным).
    if n % 3 != 0:
        return f(n - 5, t) + f(n - (n % 3), t)
    
    # Если число кратно трём, доступны команды А (вычесть 5) и С (разделить на 3).
    if n % 3 == 0:
        return f(n - 5, t) + f(n // 3, t)

# Количество путей от 103 до 24 через 73 равно произведению количества путей от 103 до 73 и от 73 до 24.
print(f(103, 73) * f(73, 24))


