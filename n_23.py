# Программа для исполнителя — это последовательность команд.
# Сколько программ существует таких, что при исходном числе 5 будет получено число 89, при этом траектория вычислений исполнителя пройдет через число 23 и не пройдет через число 50?
# Траектория вычислений программы — это последовательность результатов выполнения всех команд программы. Например, для программы 132 при исходном числе 5 траектория будет состоять из чисел 8, 9, 19.

# Идея решения:
# Требование "пройти через число 23" позволяет разбить задачу на два независимых этапа: 
# путь от 5 до 23 и путь от 23 до 89. Общее количество программ равно произведению количеств программ на каждом этапе.
# Чтобы исключить траектории, проходящие через 50, добавляем условие: если n == 50, возвращаем 0.
# Формула для "Следующее, кратное 3": n + (3 - (n % 3)). Если n уже кратно 3, это даст n + 3, что верно, так как число должно стать строго больше.

def f(n, t):
    if n == t:
        return 1
    # Превышение целевого значения или попадание в запрещённое число 50 обрывает ветку вычислений
    if n > t or n == 50:
        return 0
    # Суммируем варианты для всех трёх команд:
    # 1. n + 3
    # 2. (2 * n) + 1
    # 3. n + (3 - (n % 3)) — следующее число, кратное 3
    return f(n + 3, t) + f((2 * n) + 1, t) + f(n + (3 - (n % 3)), t)

# Перемножаем количество путей от 5 до 23 и от 23 до 89
