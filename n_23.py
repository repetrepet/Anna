# Первая команда увеличивает число на 1, вторая — на 2, третья — вдвое. Программа для исполнителя — это последовательность команд.
# Сколько существует таких программ, которые исходное число 3 преобразуют в число 25 и при этом в программе есть все три команды?

# Идея решения:
# В рекурсивную функцию передаётся строка a, в которую последовательно добавляются обозначения выполненных команд ("A", "B", "C").
# При достижении целевого числа проверяем наличие всех трёх символов в строке с помощью оператора in.
# Если все команды использованы хотя бы по одному разу, возвращаем 1. 
# Если нет, условие не выполняется, код идёт дальше, где проверка n > t обеспечит возврат 0 для этой ветки.

def f(n, t, a):
    # Если достигли цели и в строке a присутствуют все три команды
    if n == t and ("A" in a and "B" in a and "C" in a):
        return 1
    # Если превысили целевое значение, ветка не подходит
    if n > t:
        return 0
    # Рекурсивно перебираем команды, добавляя их обозначение к строке a
    return f(n + 1, t, a + "A") + f(n + 2, t, a + "B") + f(n * 2, t, a + "C")

# Начальный вызов: старт с числа 3, цель 25, пустая строка команд
print(f(3, 25, ''))
