# Исполнитель преобразует число на экране.
# У исполнителя есть три команды, которые обозначены латинскими буквами:
# **A.** Прибавить 1
# **B.** Умножить на 2
# **C.** Умножить на 3
# Программа для исполнителя — это последовательность команд.
# Сколько существует программ, для которых при исходном числе 2 результатом является 39 и при этом траектория вычислений не содержит числа 14?
# Траектория вычислений программы — это последовательность результатов выполнения всех команд программы.
# *Например, для программы АВС при исходном числе 7 траектория состоит из чисел 8, 16, 48.*

# Общая идея решения: используем рекурсивную функцию для подсчета количества путей. 
# Если текущее число равно целевому, возвращаем 1 (найден один путь). 
# Если число превысило целевое или равно запрещенному числу 14, возвращаем 0 (путь не подходит). 
# В противном случае суммируем количество путей для всех трех возможных команд.

def f(number, target):
    # Базовый случай рекурсии: если текущее число равно целевому,
    # значит, мы нашли одну валидную программу, возвращаем 1.
    if number == target:
        return 1
    
    # Если число превысило целевое значение (дальше только растет) 
    # или попало на запрещенное число 14, такой путь не подходит, возвращаем 0.
    if number > 39 or number == 14:
        return 0
    
    # Рекурсивный вызов для всех трех команд: прибавить 1, умножить на 2, умножить на 3.
    # Суммируем количество программ, полученных из каждого варианта.
    return f(number + 1, target) + f(number * 2, target) + f(number * 3, target)

print(f(2, 39))


# Исполнитель преобразует число на экране с помощью трёх команд, которым присвоены буквы латинского алфавита:
# A. Вычесть 5
# B. Сделать кратным трём
# C. Поделить на 3
# Команда А уменьшает число на экране на 5.
# Команда В может быть применена только к числам, не кратным трём, и уменьшает число на экране так, чтобы получилось ближайшее к исходному кратное трём число.
# Команда С может быть применена только к числам, кратным трём, и уменьшает число на экране в три раза.
# Программа для исполнителя — это последовательность команд.
# Сколько программ преобразуют число 103 в число 24, и при этом их траектория вычислений содержит число 73?
# Траектория вычислений программы — это последовательность результатов выполнения всех команд программы. Например, для программы АСВ при исходном числе 251 траектория состоит из чисел 246, 82, 81.

# Общая идея решения: так как траектория должна обязательно содержать число 73, 
# задачу можно разбить на две независимые части: найти количество программ от 103 до 73 
# и умножить на количество программ от 73 до 24. 
# Рекурсивная функция считает пути: если число равно целевому, возвращаем 1; 
# если стало меньше целевого, возвращаем 0. 
# Для чисел, не кратных 3, доступны команды А (вычесть 5) и В (вычесть остаток от деления на 3). 
# Для кратных 3 доступны команды А (вычесть 5) и С (разделить на 3).

def f(n, t):
    # Базовый случай: достигли целевого числа, найден 1 путь.
    if n == t:
        return 1
    
    # Если число стало меньше целевого, дальнейшее уменьшение бессмысленно, возвращаем 0.
    if n < t:
        return 0
    
    # Если число не кратно трём, доступны команды А (вычесть 5) и В (вычесть остаток от деления на 3, чтобы сделать кратным).
    if n % 3 != 0:
        return f(n - 5, t) + f(n - (n % 3), t)
    
    # Если число кратно трём, доступны команды А (вычесть 5) и С (разделить на 3).
    if n % 3 == 0:
        return f(n - 5, t) + f(n // 3, t)

# Количество путей от 103 до 24 через 73 равно произведению количества путей от 103 до 73 и от 73 до 24.
print(f(103, 73) * f(73, 24))


# Исполнитель преобразует число на экране. У исполнителя есть три команды, которые обозначены латинскими буквами:
# A. Прибавить 1
# B. Прибавить 3
# C. Умножить на 2
# Программа для исполнителя — это последовательность команд. Сколько существует программ, для которых при исходном числе 2 результатом является число 25, и при этом траектория вычислений содержит число 15 и не содержит 7?
# Траектория вычислений — это последовательность результатов выполнения всех команд программы. Например, для программы **СВА** при исходном числе 7 траектория состоит из чисел 14, 17, 18.

# Общая идея решения: аналогично предыдущей задаче, разбиваем путь на два этапа: от 2 до 15 и от 15 до 25, 
# так как число 15 обязательно должно быть в траектории. 
# Число 7 запрещено, поэтому при достижении 7 возвращаем 0. 
# Рекурсия суммирует пути для команд: прибавить 1, прибавить 3, умножить на 2.

def f(n, t):
    # Базовый случай: достигли целевого числа, возвращаем 1.
    if n == t:
        return 1
    
    # Если число превысило целевое или попало на запрещенное число 7, путь невалиден, возвращаем 0.
    if n > t or n == 7:
        return 0
    
    # Рекурсивно суммируем количество путей для всех трех доступных команд.
    return f(n + 1, t) + f(n + 3, t) + f(n * 2, t)

# Общее количество программ равно произведению количества путей от 2 до 15 и от 15 до 25.
print(f(2, 15) * f(15, 25))


# Исполнитель преобразует число, записанное на экране. У исполнителя есть четыре команды которые обозначены латинскими буквами:
# A. Прибавить 1
# B. Прибавить 2
# C. Прибавить 4
# D. Прибавить 8
# Программа исполнителя — это последовательность команд.
# Сколько существует программ, для которых при исходном числе 16 результатом является число 48, если никакую из команд нельзя повторять дважды подряд?

# Общая идея решения: используем рекурсию с дополнительным параметром `move`, 
# который хранит последнюю выполненную команду. 
# Это позволяет исключить повторение одной и той же команды подряд. 
# Если текущее число равно целевому, возвращаем 1. Если превысило, возвращаем 0. 
# В зависимости от последней команды, рекурсивно вызываем функцию только для разрешенных следующих команд.

def f(n, t, move):
    # Базовый случай: достигли целевого числа, найден 1 валидный путь.
    if n == t:
        return 1
    
    # Если число превысило целевое значение, дальнейший рост бессмысленен, возвращаем 0.
    if n > 48:
        return 0
    
    # Если последняя команда была 'A' (прибавить 1), следующая может быть только 'B', 'C' или 'D'.
    if move == 'A':
        return f(n + 2, t, 'B') + f(n + 4, t, 'C') + f(n + 8, t, 'D')
    
    # Если последняя команда была 'B' (прибавить 2), следующая может быть только 'A', 'C' или 'D'.
    if move == 'B':
        return f(n + 1, t, 'A') + f(n + 4, t, 'C') + f(n + 8, t, 'D')
    
    # Если последняя команда была 'C' (прибавить 4), следующая может быть только 'A', 'B' или 'D'.
    if move == 'C':
        return f(n + 1, t, 'A') + f(n + 2, t, 'B') + f(n + 8, t, 'D')
    
    # Если последняя команда была 'D' (прибавить 8), следующая может быть только 'A', 'B' или 'C'.
    if move == 'D':
        return f(n + 1, t, 'A') + f(n + 2, t, 'B') + f(n + 4, t, 'C')
    
    # Если это самый первый вызов (последняя команда пустая), доступны все четыре команды.
    if move == '':
        return f(n + 1, t, 'A') + f(n + 2, t, 'B') + f(n + 4, t, 'C') + f(n + 8, t, 'D')

print(f(16, 48, ''))
