# Идея решения:
# Функция count_paths(n, target) рекурсивно считает количество программ,
# переводящих число n в target. Из любого числа можно получить n + 1.
# Если предпоследняя цифра
# меньше последней, дополнительно разрешено поменять две последние цифры местами.
# Когда текущее число совпало с целью, найден один путь; если оно превысило
# цель, такой путь больше не подходит.

def swap_last_two(n):
    # Преобразуем число в строку, меняем местами две последние цифры
    # и возвращаем результат снова как целое число.
    digits = str(n)
    return int(digits[:-2] + digits[-1] + digits[-2])


def count_paths(n, target):
    # Если достигли конечного числа, текущая последовательность команд подходит.
    if n == target:
        return 1

    # Если превысили конечное число, продолжать этот путь бессмысленно.
    if n > target:
        return 0

    # Команда увеличения числа на 1 доступна всегда.
    paths = count_paths(n + 1, target)

    # Команду перестановки применяем только тогда, когда предпоследняя цифра
    # текущего числа меньше последней.
    digits = str(n)
    if int(digits[-2]) < int(digits[-1]):
        paths += count_paths(swap_last_two(n), target)

    # Возвращаем общее количество путей из текущего числа в конечное.
    return paths


# Считаем количество программ, переводящих число 100 в число 141.
print(count_paths(100, 141))
